static uint8_t color_of(char ch)
{
    switch (ch)
    {
        case '#': return C_INK;
        case 'w': return C_WHITE;
        case 'r': return C_ALERT;
        case 'b': return C_ACCENT;
        case 'B': return SEC_MID(SEC_TIMERS);
        case 'g': return C_OK;
        case 'G': return SEC_MID(SEC_TODO);
        case 'y': return C_GOLD;
        case 'Y': return SEC_MID(SEC_NOTES);
        case 'o': return C_ORANGE;
        case 'k': return C_LEATHER;
        case 'K': return C_LEATHER_HI;
        case 's': return C_INK_SOFT;
        case 'e': return C_KEY;
        case 't': return C_TEAL;
        case 'm': return C_MARGIN;
        default: return 0;   // see-through
    }
}

static void draw(Surface *s, int x, int y, int icon, int scale, int tint)
{
    int id = icon & 0xFF;
    if (id <= ICON_NONE || id >= ICON_COUNT)
        return;
    bool flip_h = (icon & ICON_FLIP_H) != 0, flip_v = (icon & ICON_FLIP_V) != 0;
    for (int r = 0; r < 16; r++)
    {
        const char *row = ART[id][flip_v ? 15 - r : r];
        for (int c = 0; c < 16; c++)
        {
            uint8_t col = color_of(row[flip_h ? 15 - c : c]);
            if (col == 0)
                continue;
            gfx_fill(s, x + c * scale, y + r * scale, scale, scale, tint >= 0 ? (uint8_t)tint : col);
        }
    }
}

void gfx_icon(Surface *s, int x, int y, int icon, int scale)
{
    draw(s, x, y, icon, scale, -1);
}

void gfx_icon_tint(Surface *s, int x, int y, int icon, int scale, uint8_t c)
{
    draw(s, x, y, icon, scale, c);
}
